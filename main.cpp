#include <string>
#include <vector>

void leading_zeros() {
    unsigned int n = 0b000101u;
    int zeros = 0;
    while ((n & 1u) == 0u) { zeros += 1; n >>= 1; }
    (void)zeros;
}

void geometric_sum() {
    int acc = 0;
    int term = 1;
    for (int i = 0; i < 8; ++i) { acc += term; term *= 2; }
    (void)acc;
}

void swap_values() {
    int a = 5, b = 11;
    int tmp = a;
    a = b;
    b = tmp;
    (void)a;
    (void)b;
}

void integer_power() {
    int base = 2, exp = 8;
    int power = 1;
    for (int i = 0; i < exp; ++i) power *= base;
    (void)power;
}

extern "C" int quiet_harbor();
extern "C" void golden_haven();
extern "C" void lucid_willow();

int main() {
    leading_zeros();
    geometric_sum();
    swap_values();
    integer_power();
    golden_haven();
    lucid_willow();
    return quiet_harbor();
}
